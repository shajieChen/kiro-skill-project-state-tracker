    out.append(f"- **Summary**: {ce.get('summary', '')}")
    out.append("")
    out.append(f"## Affected artifacts ({len(ce.get('affected') or [])})")
    for aid in ce.get("affected") or []:
        out.append(f"- `{aid}`")
    out.append("")
    out.append("## State transitions")
    out.append("| Artifact | From | To | Reason |")
    out.append("| --- | --- | --- | --- |")
    for t in ce.get("transitions") or []:
        out.append(f"| `{t.get('artifact')}` | {t.get('from')} | {t.get('to')} | {t.get('reason', '')} |")
    out.append("")
