def render_landing_readme(status: dict, project: str) -> str:
    """Generate prompts/landing/README.md body (ELP-compatible).
    
    Front-matter is preserved if the file already exists with user-edited front-matter.
    The ## LP 序列 section is also preserved if it already exists (user-authored takes priority).
    """
    meta = status.get("meta") or {}
    proj = status.get("project") or {}
    proj_name = proj.get("name") or meta.get("project_name", "Unknown Project")
    arts = status.get("artifacts") or []
    hcs = status.get("handoff_contexts") or []

    # Generate front-matter from meta
    source_root = meta.get("source_root", "<\u672a\u914d\u7f6e>")
    scope = meta.get("scope") or []
    pst_root_val = meta.get("pst_root", "<\u672a\u914d\u7f6e>")

    fm_lines = ["---"]
    fm_lines.append(f'source_root: "{source_root}"')
    if scope:
        fm_lines.append("scope:")
        for s in scope:
            fm_lines.append(f'  - "{s}"')
    if pst_root_val and "\u672a\u914d\u7f6e" not in pst_root_val:
        fm_lines.append(f'pst_root: "{pst_root_val}"')
    fm_lines.append("---")
    new_frontmatter = "\n".join(fm_lines)

    # Body
    body_lines = []
    body_lines.append(f"# {proj_name} LandingPrompt")
    body_lines.append("")
    body_lines.append("> Auto-generated body by project-state-tracker. Front-matter and LP \u5e8f\u5217 preserved if pre-existing.")
    body_lines.append(f"> Last updated: {meta.get('last_run', 'unknown')}")
    body_lines.append("")

    # LP 序列 — generated from topological sort
    lp_order = _topological_sort_lps(arts)
    body_lines.append("## LP \u5e8f\u5217")
    body_lines.append("")
    if lp_order:
        body_lines.append(" -> ".join(lp_order))
    else:
        body_lines.append("\u5c1a\u65e0\u5df2\u6ce8\u518c\u7684 Landing Prompt")
    body_lines.append("")

    # Coding Standards
    coding_standards = meta.get("coding_standards")
    if coding_standards:
        body_lines.append("## Coding Standards")
        body_lines.append("")
        body_lines.append(coding_standards)
        body_lines.append("")

    # LP status table
    lps = [a for a in arts if a.get("type") == "landing_prompt"]
    body_lines.append("## \u5f53\u524d LP \u72b6\u6001")
    body_lines.append("")
    if lps:
        body_lines.append("| ID | Status | Depends On | Produces HC |")
        body_lines.append("|----|--------|------------|-------------|")
        for lp in lps:
            deps = ", ".join(lp.get("depends_on") or []) or "(none)"
            produces = ", ".join(lp.get("produces_handoffs") or []) or "(none)"
            body_lines.append(f"| {lp.get('id')} | {lp.get('status', '?')} | {deps} | {produces} |")
    else:
        body_lines.append("\u5c1a\u65e0\u5df2\u6ce8\u518c\u7684 Landing Prompt")
    body_lines.append("")

    # Handoff summary
    lp_ids = {a.get("id") for a in lps}
    relevant_hcs = [hc for hc in hcs if hc.get("producer") in lp_ids or
                    any(c in lp_ids for c in (hc.get("consumed_by") or []))]
    body_lines.append("## Handoff \u4e0a\u4e0b\u6587\u6458\u8981")
    body_lines.append("")
    if relevant_hcs:
        body_lines.append("| HC | Facts | Constraints | Consumed By |")
        body_lines.append("|----|-------|-------------|-------------|")
        for hc in relevant_hcs:
            facts = hc.get("facts") or []
            constraints = hc.get("constraints") or []
            fact_strs = []
            for f in facts:
                if isinstance(f, dict):
                    fact_strs.append(f.get("statement", str(f.get("id", "?"))))
                else:
                    fact_strs.append(str(f))
            constraint_strs = []
            for c in constraints:
                if isinstance(c, dict):
                    constraint_strs.append(c.get("statement", str(c.get("id", "?"))))
                else:
                    constraint_strs.append(str(c))
            facts_summary = "; ".join(fact_strs[:3]) if fact_strs else "(none)"
            constraints_summary = "; ".join(constraint_strs[:3]) if constraint_strs else "(none)"
            consumers = ", ".join(hc.get("consumed_by") or []) or "(none)"
            body_lines.append(f"| {hc.get('id')} | {facts_summary} | {constraints_summary} | {consumers} |")
    else:
        body_lines.append("(\u65e0\u6d3b\u8dc3 handoff)")
    body_lines.append("")

    new_body = "\n".join(body_lines)
    return new_frontmatter + "\n\n" + new_body


def write_landing_readme_with_preservation(path: str, new_content: str, status: dict):
    """Write landing README preserving user front-matter and user-authored LP sequence.
    
    Preservation rules:
    1. If file exists with YAML front-matter -> preserve the front-matter, replace body
    2. If file exists with a user-authored LP sequence section -> preserve that section
       (detected by: section content differs from what topological sort would generate)
    3. If file does not exist -> write new_content as-is
    """
    if not os.path.isfile(path):
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as f:
            f.write(new_content)
        return

    existing = ""
    with open(path, "r", encoding="utf-8") as f:
        existing = f.read()

    # Extract existing front-matter
    existing_fm = ""
    existing_body = existing
    if existing.startswith("---"):
        second_dash = existing.find("---", 3)
        if second_dash != -1:
            existing_fm = existing[:second_dash + 3]
            existing_body = existing[second_dash + 3:].lstrip("\n")

    # Extract existing LP sequence section (## LP 序列)
    existing_lp_section = None
    lp_heading = "## LP \u5e8f\u5217"
    lp_pattern = re.compile(r"(## LP \u5e8f\u5217\s*\n)(.*?)(?=\n## |\Z)", re.DOTALL)
    lp_match = lp_pattern.search(existing_body)
    if lp_match:
        existing_lp_section = lp_match.group(0).strip()

    # Parse new content into front-matter and body
    new_fm = ""
    new_body = new_content
    if new_content.startswith("---"):
        second_dash = new_content.find("---", 3)
        if second_dash != -1:
            new_fm = new_content[:second_dash + 3]
            new_body = new_content[second_dash + 3:].lstrip("\n")

    # Use existing front-matter if present, otherwise use generated
    final_fm = existing_fm if existing_fm else new_fm

    # If existing LP sequence exists and differs from generated, preserve it
    if existing_lp_section:
        new_lp_match = lp_pattern.search(new_body)
        if new_lp_match:
            generated_lp = new_lp_match.group(0).strip()
            if existing_lp_section != generated_lp:
                # User has customized LP sequence — preserve it
                new_body = new_body[:new_lp_match.start()] + existing_lp_section + "\n" + new_body[new_lp_match.end():]

    final = final_fm + "\n\n" + new_body if final_fm else new_body
    with open(path, "w", encoding="utf-8") as f:
        f.write(final)



